#!/usr/bin/env python3
"""Results-only deck: what we measured, where the variance is, and why.

Separate from scripts/make_deck.py (the full 23-slide talk). This one assumes
the audience already knows the pipeline and goes straight at the findings, in
the order they were established:

    demonstrations are worse as data  ->  policies trained on them are worse
    ->  the damage is in the ARM, not the hand  ->  the arm is where a
    stochastic planner drives  ->  so the mechanism is planner
    non-determinism, not operator inconsistency

Same format rules as the main deck: Arial, black text, white ground, CMU red
for the rule only, citations small on the slide that discusses the work, no
boxes around text.

Figures are generated by scripts/plot_variance.py and
scripts/plot_trajectories.py; this script only lays them out, so re-run those
first if the data changes.

Usage:  uv run python scripts/make_results_deck.py
"""
from __future__ import annotations

import argparse
from pathlib import Path

from pptx import Presentation
from pptx.util import Emu, Pt

from make_deck import (BLACK, BODY_H, BODY_T, CMU_RED, EMU_IN, SLIDE_H,
                       SLIDE_W, SZ_CITE, SZ_KICKER, SZ_L0, SZ_L1, SZ_TITLE,
                       TITLE_H, TITLE_L, TITLE_T, TITLE_W, WHITE, _blank,
                       _para, _rule, _textbox, content, table_slide)

FIGS = Path("docs/figs")


def figure_slide(prs, title, image: Path, kicker=None, notes=(), cite=None,
                 img_frac=0.62):
    """A slide whose body is one figure, with optional bullets beneath it."""
    slide = _blank(prs)
    _, tf = _textbox(slide, TITLE_L, TITLE_T, TITLE_W, TITLE_H)
    used: list = []
    _para(tf, used, title, SZ_TITLE, bold=True)
    _rule(slide)

    top = BODY_T
    if kicker:
        _, tf = _textbox(slide, TITLE_L, top, TITLE_W, int(0.40 * EMU_IN))
        used = []
        _para(tf, used, kicker, SZ_KICKER, bold=True)
        top += int(0.52 * EMU_IN)

    n_note = len(notes)
    n_cite = len(cite or ())
    reserve = int((n_note * 0.30 + n_cite * 0.26 + 0.18) * EMU_IN)
    avail_h = (BODY_T + BODY_H) - top - reserve

    if image.exists():
        from PIL import Image
        with Image.open(image) as im:
            iw, ih = im.size
        h = min(avail_h, int(TITLE_W * ih / iw))
        w = int(h * iw / ih)
        if w > TITLE_W:
            w, h = TITLE_W, int(TITLE_W * ih / iw)
        slide.shapes.add_picture(str(image), Emu(TITLE_L + (TITLE_W - w) // 2),
                                 Emu(top), width=Emu(w), height=Emu(h))
        top += h + int(0.14 * EMU_IN)
    else:
        _, tf = _textbox(slide, TITLE_L, top, TITLE_W, int(0.4 * EMU_IN))
        used = []
        _para(tf, used, f"[missing figure: {image}]", SZ_L1)
        top += int(0.5 * EMU_IN)

    if notes:
        _, tf = _textbox(slide, TITLE_L, top, TITLE_W,
                         int(n_note * 0.30 * EMU_IN))
        used = []
        for n in notes:
            _para(tf, used, n, SZ_L1, bullet=True, space_before=3)
        top += int(n_note * 0.30 * EMU_IN)

    if cite:
        _, tf = _textbox(slide, TITLE_L, top + int(0.08 * EMU_IN), TITLE_W,
                         int(n_cite * 0.28 * EMU_IN))
        used = []
        for c in cite:
            _para(tf, used, c, SZ_CITE)
    return slide


def build(out: Path) -> Path:
    prs = Presentation()
    prs.slide_width = Emu(SLIDE_W)
    prs.slide_height = Emu(SLIDE_H)

    # ---- 1. title -------------------------------------------------------
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    bg = slide.background
    bg.fill.solid()
    bg.fill.fore_color.rgb = CMU_RED
    _, tf = _textbox(slide, 670560, 2200000, 10850880, 1800000)
    used: list = []
    _para(tf, used, "Where the Variance Is", 4000, bold=True, color=WHITE)
    _para(tf, used, "Contact-aware vs baseline demonstrations", 2200,
          color=WHITE, space_before=14)
    _, tf = _textbox(slide, 670560, 4700000, 10850880, 1200000)
    used = []
    _para(tf, used, "Suresh Kumaar Jayaraman", 2000, color=WHITE)
    _para(tf, used, "22 October 2026", 1600, color=WHITE, space_before=10)

    # ---- 2. the chain of findings ---------------------------------------
    content(
        prs, "What we found, in order",
        kicker="Each step was measured, and each narrowed the cause.",
        blocks=[
            ("1.  The demonstrations are worse as data", 0),
            ("Action divergence 1.74–2.12× worse — before any "
             "policy is trained.", 1),
            ("2.  Policies trained on them are worse", 0),
            ("3.6× BC-MLP, 3.9× BC-RNN, 1.7× ACT. Three "
             "architectures, same sign.", 1),
            ("3.  The damage is in the ARM, not the hand", 0),
            ("Per-block validation loss: arm ~7.5–7.9×, hand "
             "2.6–3.2×.", 1),
            ("4.  The arm is where a stochastic planner drives", 0),
            ("59% of contact-aware frames are RRT output. Baseline has none.", 1),
            ("So the mechanism is planner non-determinism — not operator "
             "inconsistency.", 0),
        ])

    # ---- 3. learnability, three architectures ---------------------------
    table_slide(
        prs, "Policies trained on contact-aware data are worse",
        kicker="Validation loss on held-out episodes — lower is better.",
        headers=["Algorithm", "Baseline", "Contact-aware", "Gap"],
        rows=[["BC-MLP  (8-fold CV, 12 seeds)", "0.0968", "0.3477", "*3.6×"],
              ["BC-RNN  (8-fold CV, 6 seeds)", "0.0851", "0.3362", "*3.9×"],
              ["ACT  (8-fold CV, 6 seeds)", "0.1896", "0.3199", "*1.7×"]],
        notes=["Cohen d = −8.08, −9.80, −8.16. All p < 0.0001.",
               "Losses are NOT comparable across algorithms — MSE for BC, L1+KL for ACT. Only the within-row ratio is meaningful.",
               "ACT narrows the gap most, as its chunking and CVAE latent should. It does not close it.",
               "robomimic identifies BC-RNN as the architecture most tolerant of mixed-quality data. It did not rescue this."])

    # ---- 4. the arm/hand split ------------------------------------------
    table_slide(
        prs, "The damage is in the arm, not the hand",
        kicker="Same training runs, validation loss split by joint block.",
        headers=["Block", "BC-MLP", "BC-RNN"],
        rows=[["Pooled  (23 joints)", "3.36×", "3.95×"],
              ["Arm  (7 joints)", "*7.86×", "*7.51×"],
              ["Hand  (16 joints)", "2.60×", "3.20×"]],
        notes=["Both blocks significant (d = −10.3 and −9.0), but the arm gap is ~3× the hand gap.",
               "This closes the obvious objection: the FINGER labels were partly reconstructed, the ARM labels never were — and the arm is where the gap is.",
               "Baseline's own structure inverts: there the hand is the harder block (0.121 vs 0.047). Certification made the arm the hard part."])

    # ---- 5. THE FIGURE --------------------------------------------------
    figure_slide(
        prs, "Where the demonstrations disagree",
        FIGS / "variance.png",
        kicker="Every episode resampled to 100 normalised-time points; spread taken across episodes.",
        notes=["Both conditions start tight (~4.5 cm). Baseline re-converges by the end (9.0 cm); contact-aware stays wide (18.8 cm).",
               "Dotted lines are contact-aware lock-in times — they span 2% to 31% of the trial.",
               "Note the paradox, bottom left: contact-aware paths are SHORTER and more uniform in LENGTH (sd 0.29 m vs 0.85 m). Tidier motion, less learnable data."])

    # ---- 6. reading the figure ------------------------------------------
    content(
        prs, "Reading that figure",
        kicker="Three things it shows that a ratio cannot.",
        blocks=[
            ("The disagreement is not uniform in time", 0),
            ("Baseline peaks mid-trial (the operator hunting for a grasp) then "
             "converges as the task completes.", 1),
            ("Contact-aware peaks LATE and stays there — the episodes end "
             "in different places.", 1),
            ("Lock-in timing is scattered, not clustered", 0),
            ("The planner takes over anywhere from 2% to 31% of the way "
             "through, so no two episodes hand over at the same stage.", 1),
            ("Shorter paths, worse data", 0),
            ("Contact-aware motion is tidier by path length and more uniform "
             "in duration — the smoothness metrics the curation "
             "literature favours would score it BETTER.", 1),
            ("Those metrics would have been wrong here.", 1),
        ])

    # ---- 7. the RRT finding ---------------------------------------------
    table_slide(
        prs, "What drives the arm after lock-in",
        kicker="Over half of each contact-aware episode is planner output, and it is in the labels.",
        headers=["", "Baseline", "Contact-aware"],
        rows=[["RRT-driven share of frames", "0%", "*59% mean"],
              ["Range across episodes", "—", "24–86%"],
              ["Hand-over event", "none", "lock-in, 2–31%"]],
        notes=["extract.py reads control_phase only to pick a label-recovery method — it never filters rows, so PLAN and REACH frames are training labels.",
               "RRT is sampling-based: the same start and goal give a different path every call.",
               "So the pipeline replaced variable HUMAN arm motion with variable PLANNER arm motion — and the planner's variation is unconditioned on anything the policy observes."])

    # ---- 8. trajectories ------------------------------------------------
    figure_slide(
        prs, "One episode each, success and failure",
        FIGS / "trajectories.png",
        kicker="Contact-aware panels are phase-coloured; marker size grows with time.",
        notes=["The piecewise-linear blue segments in the contact-aware panels are RRT waypoints, not human motion.",
               "Baseline failure (top right, 39 s) shows the operator looping near the object — a different failure mode entirely.",
               "Caveat: both failures are 'abandoned' trials from outside the 31-episode comparison set, which kept successes only."])

    # ---- 9. why this is the opposite of the expectation ------------------
    content(
        prs, "Why shared autonomy made this worse",
        kicker="Assistance did reduce variability — in the part it directly controls.",
        blocks=[
            ("Where the certificate helped", 0),
            ("Hand action VARIANCE is 0.80× — the one metric where "
             "contact-aware wins. The certified squeeze is more repeatable.", 1),
            ("Where it hurt", 0),
            ("Arm action variance 1.80× worse; arm validation loss ~7.5× "
             "worse. The approach to the grasp is what fell apart.", 1),
            ("The mechanism", 0),
            ("The certificate hands control to a stochastic planner at an "
             "unpredictable moment. Variability was not removed — it was "
             "relocated from the fingers to the arm, and made less learnable "
             "on the way.", 1),
            ("A human's variation correlates with the scene; RRT's correlates "
             "with its random seed.", 1),
        ])

    # ---- 10. what the theory predicted ----------------------------------
    content(
        prs, "The theory predicted this",
        kicker="Belkhale et al. named the tradeoff before we ran the experiment.",
        blocks=[
            ("Their two properties", 0),
            ("Action divergence predicts policy success. State diversity does "
             "NOT — they measure it as uncorrelated.", 1),
            ("What we bought and paid", 0),
            ("State diversity up 22%; action divergence up ~2×. We "
             "optimised the metric that does not matter and degraded the one "
             "that does.", 1),
            ("Their sentence about prior work", 0),
            ("It “aim[s] to maximize state diversity through shared "
             "control” while leaving the action side unexamined.", 1),
            ("That describes this pipeline.", 1),
        ],
        cite=["Belkhale, Cui & Sadigh, Data Quality in Imitation Learning, NeurIPS 2023."])

    # ---- 11. next test --------------------------------------------------
    content(
        prs, "The test this suggests",
        kicker="If the planner is the cause, making it deterministic should close the arm gap.",
        blocks=[
            ("Cheaper and more specific than the fixed-timing arm", 0),
            ("Fix the RRT seed, or post-process to a smoothed/optimised path, "
             "and keep everything else identical.", 1),
            ("Prediction: arm loss falls toward baseline while the 94% task "
             "success is preserved.", 1),
            ("Three arms, same collection budget", 0),
            ("baseline  ·  contact-aware  ·  contact-aware with a "
             "deterministic planner.", 1),
            ("Also worth logging", 0),
            ("The lock-in timestamp explicitly — it is currently "
             "reconstructed from events, which makes the central quantity an "
             "inference.", 1),
            ("Open question: is a certificate that admits many valid paths "
             "inherently at odds with learnable demonstrations?", 0),
        ])

    # ---- 12. summary ----------------------------------------------------
    content(
        prs, "Summary",
        kicker="One sentence: the certificate improved the grasp and degraded the reach.",
        blocks=[
            ("Measured", 0),
            ("Demonstrations 1.74–2.12× worse by action divergence; "
             "policies 1.7–3.9× worse across three architectures; "
             "task success 94% vs 69%.", 1),
            ("Localised", 0),
            ("Arm ~7.5–7.9× vs hand 2.6–3.2×. Hand variance "
             "is the single metric favouring contact-aware.", 1),
            ("Explained — provisionally", 0),
            ("59% of contact-aware frames are stochastic-planner output, "
             "entering at a hand-over that lands anywhere from 2% to 31% "
             "through the trial.", 1),
            ("Not yet causally established. The deterministic-planner arm "
             "tests it.", 1),
        ])

    out.parent.mkdir(parents=True, exist_ok=True)
    prs.save(str(out))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path,
                    default=Path("docs/IL_results.pptx"))
    args = ap.parse_args()
    print(f"-> {build(args.out)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
